-- 每次 study_state 被更新前，把旧的一版存进来
create table if not exists public.study_state_history (
  id          bigint generated by default as identity primary key,
  user_id     uuid        not null,
  rev         bigint      not null,
  data        jsonb       not null,
  updated_at  timestamptz not null,
  archived_at timestamptz not null default now()
);

comment on table public.study_state_history is '学业工作台：云同步历史快照，每次写入前自动归档上一版';

create index if not exists study_state_history_user_idx
  on public.study_state_history (user_id, id desc);

alter table public.study_state_history enable row level security;

-- 只读自己的历史；写入只允许触发器（security definer）完成
drop policy if exists "study_state_history_select_own" on public.study_state_history;
create policy "study_state_history_select_own"
  on public.study_state_history for select
  to authenticated
  using (auth.uid() = user_id);

grant select on public.study_state_history to authenticated;
revoke all on public.study_state_history from anon;

-- 归档 + 只保留最近 20 版，避免表无限增长
create or replace function public.study_state_archive()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.study_state_history (user_id, rev, data, updated_at)
  values (old.user_id, old.rev, old.data, old.updated_at);

  delete from public.study_state_history
  where user_id = old.user_id
    and id not in (
      select id
      from public.study_state_history
      where user_id = old.user_id
      order by id desc
      limit 20
    );

  return new;
end;
$$;

drop trigger if exists study_state_archive on public.study_state;
create trigger study_state_archive
  after update on public.study_state
  for each row execute function public.study_state_archive();

